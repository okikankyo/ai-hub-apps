async function seed() {
  const userCount = (await db.prepare('SELECT COUNT(*) AS n FROM users').get()).n;
  if (Number(userCount) > 0) return;
  const insDept = db.prepare('INSERT INTO departments (name, monthly_budget_jpy) VALUES (?, ?)');
  const adminDeptId = (await insDept.run('管理部', 30000)).lastInsertRowid;
  const salesDeptId = (await insDept.run('営業部', 50000)).lastInsertRowid;
  await insDept.run('開発部', 100000);
  const insUser = db.prepare(
    'INSERT INTO users (username, display_name, password_hash, role, department_id) VALUES (?, ?, ?, ?, ?)'
  );
  await insUser.run('admin', '管理者', hashPassword('admin1234'), 'admin', adminDeptId);
  await insUser.run('demo', 'デモユーザー', hashPassword('demo1234'), 'user', salesDeptId);
  console.log('[db] 初期データを作成しました');
}

function hashPassword(password) {
  const salt = crypto.randomBytes(16).toString('hex');
  const hash = crypto.scryptSync(password, salt, 32).toString('hex');
  return `${salt}:${hash}`;
}

function verifyPassword(password, stored) {
  const [salt, hash] = String(stored).split(':');
  if (!salt || !hash) return false;
  const candidate = crypto.scryptSync(password, salt, 32).toString('hex');
  return crypto.timingSafeEqual(Buffer.from(hash, 'hex'), Buffer.from(candidate, 'hex'));
}

function currentMonth() {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}`;
}

