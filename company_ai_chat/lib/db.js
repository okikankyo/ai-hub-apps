// Database layer.
//
// Local development keeps using the existing SQLite file. When DATABASE_URL
// is set, the same small adapter uses Neon/PostgreSQL. The application calls
// get/all/run asynchronously in both modes, so Cloud Run does not depend on
// an instance-local database.
'use strict';

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const DATA_DIR = process.env.DATA_DIR || path.join(__dirname, '..', 'data');
const DATABASE_URL = process.env.DATABASE_URL || '';
const USE_POSTGRES = Boolean(DATABASE_URL);

let sqlite = null;
let pool = null;

if (USE_POSTGRES) {
  const { Pool } = require('pg');
  pool = new Pool({
    connectionString: DATABASE_URL,
    ssl: process.env.DATABASE_SSL === 'false' ? false : { rejectUnauthorized: false },
    max: Number(process.env.DATABASE_POOL_MAX || 5),
    idleTimeoutMillis: 30_000,
  });
} else {
  const { DatabaseSync } = require('node:sqlite');
  fs.mkdirSync(DATA_DIR, { recursive: true });
  sqlite = new DatabaseSync(path.join(DATA_DIR, 'app.db'));
}

function normalizeSql(sql) {
  return String(sql)
    .replace(/strftime\('%Y-%m',\s*created_at\)/g, "to_char(created_at, 'YYYY-MM')")
    .replace(/CAST\(strftime\('%d',\s*created_at\) AS INTEGER\)/g, 'EXTRACT(DAY FROM created_at)::integer')
    .replace(/datetime\('now',\s*'localtime'\)/g, 'CURRENT_TIMESTAMP');
}

function postgresSql(sql) {
  let index = 0;
  return normalizeSql(sql).replace(/\?/g, () => `$${++index}`);
}

function isInsertWithId(sql) {
  return /^\s*INSERT\s+INTO\s+(?!sessions\b)/i.test(sql) && !/\bRETURNING\b/i.test(sql);
}

function prepare(sql) {
  if (!USE_POSTGRES) {
    const statement = sqlite.prepare(sql);
    return {
      async get(...params) { return statement.get(...params); },
      async all(...params) { return statement.all(...params); },
      async run(...params) {
        const result = statement.run(...params);
        return { ...result, lastInsertRowid: Number(result.lastInsertRowid || 0) };
      },
    };
  }

  const original = normalizeSql(sql);
  const queryText = postgresSql(original);
  return {
    async get(...params) {
      const result = await pool.query(queryText, params);
      return result.rows[0];
    },
    async all(...params) {
      const result = await pool.query(queryText, params);
      return result.rows;
    },
    async run(...params) {
      const text = isInsertWithId(original) ? `${queryText} RETURNING id` : queryText;
      const result = await pool.query(text, params);
      return {
        changes: result.rowCount,
        lastInsertRowid: Number(result.rows[0]?.id || 0),
      };
    },
  };
}

async function exec(sql) {
  if (USE_POSTGRES) {
    await pool.query(normalizeSql(sql));
  } else {
    sqlite.exec(sql);
  }
}

